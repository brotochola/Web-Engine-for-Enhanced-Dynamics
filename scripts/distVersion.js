// distVersion.js - is the checked-in dist/ bundle the same engine as src/?
//
// The bench pages decide with an importmap: by default `/src/index.js` resolves
// to `/dist/weed.bundle.esm.min.js`, and only `?src=1` loads live src/ modules.
// That default is a trap. `dist/` is a build artifact: it is committed, it goes
// stale silently, and nothing in the harness detects it. A stale bundle does not
// always crash - it just quietly measures a different engine than the one in the
// working tree, which is worse.
//
// Both sides are read, never guessed:
//   src  : the VERSION literal in src/version.js (generated by syncVersion.js)
//   dist : dist/.build-version, written by buildBundle.js from that same file
//
// An earlier revision of this file extracted the version by scanning the bundle
// for a semver literal. That does not work: the vendored PixiJS contributes
// 8.0.0, 8.6.1, 8.8.0, 8.15.0, 8.20.0 and 8.20.1 alongside ours, so the scan
// cannot tell which literal is the engine's. The build now writes an explicit
// stamp and this reads a file instead of parsing minified output.
//
// A missing or unreadable stamp blocks the run. That is deliberate: a dist/
// built by an older buildBundle.js has no stamp and we cannot tell what it
// contains. A false block costs one rebuild; a false pass costs a wrong verdict.

import fs from 'node:fs';
import path from 'node:path';

/** Bundle the bench importmap points at when src=1 is absent. */
export const DEFAULT_DIST_BUNDLE = 'weed.bundle.esm.min.js';

/** Written by scripts/buildBundle.js. See BUILD_STAMP_FILE there. */
export const BUILD_STAMP_FILE = '.build-version';

const SRC_VERSION_FILE = path.join('src', 'version.js');

/** VERSION written by scripts/syncVersion.js: export const VERSION = '0.7.941'; */
export function readSrcVersion(repoRoot) {
  const file = path.join(repoRoot, SRC_VERSION_FILE);
  if (!fs.existsSync(file)) return null;
  const text = fs.readFileSync(file, 'utf8');
  const m = /VERSION\s*=\s*['"]([^'"]+)['"]/.exec(text);
  return m ? m[1] : null;
}

/** Contents of dist/.build-version, or null when absent or unreadable. */
export function readDistStamp(repoRoot) {
  const file = path.join(repoRoot, 'dist', BUILD_STAMP_FILE);
  if (!fs.existsSync(file)) return null;
  try {
    const value = fs.readFileSync(file, 'utf8').trim();
    return value || null;
  } catch {
    return null;
  }
}

/**
 * @returns {{ok: boolean, srcVersion: string|null, distVersion: string|null,
 *            reason: 'fresh'|'missing'|'unstamped'|'stale'|'src-version-unreadable',
 *            message: string}}
 */
export function checkDistFresh(repoRoot, bundleName = DEFAULT_DIST_BUNDLE) {
  const srcVersion = readSrcVersion(repoRoot);
  const distPath = path.join(repoRoot, 'dist', bundleName);

  if (!fs.existsSync(distPath)) {
    return {
      ok: false,
      srcVersion,
      distVersion: null,
      reason: 'missing',
      message: `dist/${bundleName} does not exist.\n  Run: npm run make_bundle`,
    };
  }

  const distVersion = readDistStamp(repoRoot);

  if (!srcVersion) {
    // Cannot judge. Do not block the run on a missing reader.
    return {
      ok: true,
      srcVersion: null,
      distVersion,
      reason: 'src-version-unreadable',
      message: `Could not read VERSION from ${SRC_VERSION_FILE}; dist freshness not checked.`,
    };
  }

  if (!distVersion) {
    return {
      ok: false,
      srcVersion,
      distVersion: null,
      reason: 'unstamped',
      message:
        `dist/${BUILD_STAMP_FILE} is missing or empty, so this tree cannot prove which engine\n` +
        `  dist/ was built from (bundles predating the stamp). Run: npm run make_bundle`,
    };
  }

  if (distVersion !== srcVersion) {
    return {
      ok: false,
      srcVersion,
      distVersion,
      reason: 'stale',
      message:
        `dist/ was built from version ${distVersion}, src/version.js is ${srcVersion}.\n` +
        `  A run without --src would measure ${distVersion}, not the working tree.\n` +
        `  Fix: npm run make_bundle   (or pass --src to measure src/ directly)`,
    };
  }

  return {
    ok: true,
    srcVersion,
    distVersion,
    reason: 'fresh',
    message: `dist ${distVersion} matches src ${srcVersion}.`,
  };
}

/**
 * Guard for a bench entry point. No-op when the run measures src/ directly.
 * Throws so a wrong-engine run cannot be recorded as a result.
 *
 * @param {string} repoRoot
 * @param {{ useSrc?: boolean, bundleName?: string, label?: string }} [opts]
 * @returns {ReturnType<typeof checkDistFresh> | null} null when the run uses src/
 */
export function assertDistFreshForRun(repoRoot, opts = {}) {
  const { useSrc = false, bundleName = DEFAULT_DIST_BUNDLE, label = 'bench run' } = opts;
  if (useSrc) return null;

  const result = checkDistFresh(repoRoot, bundleName);
  if (result.ok) {
    if (result.reason === 'src-version-unreadable') {
      console.warn(`[distVersion] ${label}: ${result.message}`);
    }
    return result;
  }

  throw new Error(
    `[distVersion] ${label} refused to start (${result.reason}).\n\n${result.message}\n\n` +
      `This guard exists because a stale dist/ measures a different engine than the\n` +
      `one in the working tree, and the mismatch is invisible in the output.`,
  );
}
